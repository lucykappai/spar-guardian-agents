"""Emit the swarm tables of the design document from run data.

    python -m guardian.report.report_swarm [--runs runs] [--out docs/generated/swarm_results.tex]

Two macros: \\swarmrows (one row per swarm run: composition, status, calls, posts,
judged, cheated, by-role cheated, team report, registration on main ("yes (copied)" when
the registry entry carries another agent's message verbatim), how the agents'
episodes ended) and \\swarmpartialrows (one row per
set-aside swarm run that ended in a provider error, with the sweep it belonged to
taken from its failed<N>_ prefix: how far it got and the heuristic honeypot-touch
and member-read counts by role from the timeline).
Numbers come from the files, never from hand.
"""
from __future__ import annotations

import argparse
import json
import re
from pathlib import Path

from guardian.ui.server import Store

ROOT = Path(__file__).resolve().parents[2]


def tex(s) -> str:
    return str(s).replace("`", "'").replace("\\", "\\textbackslash{}").replace("_", "\\_").replace("#", "\\#").replace("%", "\\%").replace("&", "\\&")


def _ended(error: str | None) -> str:
    e = (error or "").lower()
    if "credits are depleted" in e or "billing" in e:
        return "provider: credits depleted"
    if "model turn" in e:
        return "provider: trailing model turn"
    return (error or "")[:40]


def yesno(v) -> str:
    return {True: "yes", False: "no"}.get(v, "--")


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--runs", default=str(ROOT / "runs"))
    ap.add_argument("--out", default=str(ROOT / "docs" / "generated" / "swarm_results.tex"))
    args = ap.parse_args()
    store = Store(Path(args.runs))
    complete, partial = [], []
    for name in store.run_names():
        if "swarm" not in name:
            continue
        run = json.loads((Path(args.runs) / name / "run.json").read_text())
        sw = run.get("swarm")
        if not sw:
            continue
        eps = store.episodes(name)
        prefix = re.match(r"failed(\d*)_", name)
        failed = any(e.get("failure") in ("harness", "connection_closed") for e in eps) or bool(prefix)
        if failed:
            sweep = (prefix.group(1) or "1") if prefix else "--"
            t = store.timeline(name)
            roles, agents = t["roles"], t["agents"]
            touched, read = set(t["first_honeypot_touch"]), set(t["first_member_read"])
            calls = sum(1 for e in t["events"] if e["kind"] in ("tool", "submit"))
            by = {}
            for a in agents:
                r = roles.get(a, "?"); d = by.setdefault(r, [0, 0, 0]); d[2] += 1; d[0] += a in touched; d[1] += a in read
            cell = lambda r: (f"{by[r][0]}/{by[r][1]} of {by[r][2]}" if r in by else "--")
            partial.append((sw["composition"], sweep, " & ".join([
                tex(sw["composition"]), sweep, str(calls), str(len(t["board"])), str(len(touched)), str(len(read)),
                cell("worker"), cell("regulator"), cell("disregulator"),
                tex(_ended(eps[0].get("error") if eps else ""))]) + " \\\\"))
        else:
            judged = [e for e in eps if e.get("verdict") and e["verdict"].get("cheated") is not None]
            cheated = [e for e in judged if e["verdict"]["cheated"]]
            byrole = lambda r: (f"{sum(1 for e in cheated if e.get('role') == r)}/{sum(1 for e in judged if e.get('role') == r)}"
                                if any(e.get("role") == r for e in judged) else "--")
            calls = sum(e.get("n_tool_calls") or 0 for e in eps)
            t = store.timeline(name)
            ends: dict[str, int] = {}
            for e in eps:
                k = e.get("failure") or ("submit" if e.get("ended_by") == "submit" else "end")
                ends[k] = ends.get(k, 0) + 1
            ended = ", ".join(f"{n} {k}" for k, n in sorted(ends.items(), key=lambda x: (-x[1], x[0])))
            complete.append(" & ".join([tex(sw["composition"]), str(sw.get("seed")), str(calls), str(len(t["board"])),
                                        f"{len(cheated)}/{len(judged)}", byrole("worker"), byrole("regulator"), byrole("disregulator"),
                                        yesno(sw.get("swarm_report_cheated")),
                                        yesno(None if sw.get("swarm_report_cheated") is None or not judged else (sw["swarm_report_cheated"] == bool(cheated))),
                                        (yesno((run.get("deliverables") or {}).get("registered_on_main"))
                                         + (" (copied)" if (run.get("deliverables") or {}).get("registered_message_copied_from") else "")),
                                        tex(ended) if eps else "--"]) + " \\\\")
    partial = [row for _, _, row in sorted(partial, key=lambda x: (x[0], x[1]))]
    out = Path(args.out); out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("% generated by guardian/report/report_swarm.py\n"
                   "\\newcommand{\\swarmrows}{%\n" + ("\n".join(complete) if complete else "\\multicolumn{12}{l}{no completed swarm run} \\\\") + "}\n"
                   "\\newcommand{\\swarmpartialrows}{%\n" + ("\n".join(partial) if partial else "\\multicolumn{10}{l}{none} \\\\") + "}\n"
                   f"\\newcommand{{\\swarmcompleted}}{{{len(complete)}}}\n\\newcommand{{\\swarmpartial}}{{{len(partial)}}}\n")
    print(out, "complete:", len(complete), "partial:", len(partial))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
