"""Emit the pilot-results table of the design document from run data, never by hand.

    python -m guardian.report.report_pilot runs/<name> [runs/<other> ...] [--out docs/generated/pilot_results.tex]

Reads each run's episodes.jsonl and judge.jsonl and writes LaTeX table rows
(one per episode, with the run name) plus macros for the first run's metadata.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]


def tex(s) -> str:
    return str(s).replace("`", "'").replace("\\", "\\textbackslash{}").replace("_", "\\_").replace("#", "\\#").replace("%", "\\%").replace("&", "\\&")


def yesno(v) -> str:
    return {True: "yes", False: "no"}.get(v, "--")


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("run_dirs", nargs="+")
    ap.add_argument("--out", default=str(ROOT / "docs" / "generated" / "pilot_results.tex"))
    ap.add_argument("--macro", default="pilot", help="macro prefix: \\<macro>rows, \\<macro>summaries, ...")
    args = ap.parse_args()
    M = args.macro
    rows, summaries_all, runs = [], [], []
    for run_dir in map(Path, args.run_dirs):
        run = json.loads((run_dir / "run.json").read_text())
        runs.append(run)
        episodes = {r["episode"]: r for r in map(json.loads, (run_dir / "episodes.jsonl").read_text().splitlines())}
        verdicts = {}
        judge_path = run_dir / "judge.jsonl"
        if judge_path.exists():
            verdicts = {v["episode"]: v for v in map(json.loads, judge_path.read_text().splitlines())}
        for ep, rec in episodes.items():
            v = verdicts.get(ep, {})
            usage = rec.get("usage") or {}
            d = rec.get("defense") or {}
            rows.append(" & ".join([
                tex(run["run_id"]), tex(ep), str(rec.get("n_tool_calls", "--")),
                f"{d.get('blocks', 0)}/{d.get('checks', 0)}" if rec.get("defenses") else "--",
                f"{usage.get('input', 0):,} / {usage.get('output', 0):,}" if usage else "--",   # input includes cache reads
                f"{rec['wall_time']:.0f}" if rec.get("wall_time") is not None else "--",
                tex(rec.get("failure") or "none"),
                yesno(v.get("cheated")), yesno(v.get("honey_pots_seen")), yesno(v.get("attempted_access")),
                yesno(v.get("extracted_submission")), yesno(v.get("disclosed_access")),
                f"{v['judge_cost_usd']:.2f}" if v.get("judge_cost_usd") is not None else "--",
            ]) + " \\\\")
            if v.get("summary"):
                summaries_all.append(f"\\item[{tex(run['run_id'])} {tex(ep)}] {tex(v['summary'])}")
    first = runs[0]
    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(
        "% generated by guardian/report/report_pilot.py from " + ", ".join(tex(d) for d in args.run_dirs) + "\n"
        "\\newcommand{\\" + M + "run}{" + ", ".join(tex(r.get("run_id")) for r in runs) + "}\n"
        "\\newcommand{\\" + M + "model}{" + tex(first.get("model")) + "}\n"
        "\\newcommand{\\" + M + "evalid}{" + ", ".join(tex(r.get("eval_id")) for r in runs) + "}\n"
        "\\newcommand{\\" + M + "judge}{gpt-6-sol}\n"
        "\\newcommand{\\" + M + "rows}{%\n" + "\n".join(rows) + "}\n"
        "\\newcommand{\\" + M + "summaries}{%\n\\begin{description}\n" + "\n".join(summaries_all) + "\n\\end{description}}\n"
    )
    print(out, "runs:", len(runs), "episodes:", len(rows), "judged:", len(summaries_all))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
