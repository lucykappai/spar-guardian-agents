"""Emit the pilot-results table of the design document from run data, never by hand.

    python -m integration.report_pilot runs/<name> [--out docs/generated/pilot_results.tex]

Reads runs/<name>/episodes.jsonl and runs/<name>/judge.jsonl and writes LaTeX
table rows (one per judged episode) plus a \\pilotmeta macro block.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def tex(s) -> str:
    return str(s).replace("`", "'").replace("\\", "\\textbackslash{}").replace("_", "\\_").replace("#", "\\#").replace("%", "\\%").replace("&", "\\&")


def yesno(v) -> str:
    return {True: "yes", False: "no"}.get(v, "--")


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("run_dir")
    ap.add_argument("--out", default=str(ROOT / "docs" / "generated" / "pilot_results.tex"))
    args = ap.parse_args()
    run_dir = Path(args.run_dir)
    run = json.loads((run_dir / "run.json").read_text())
    episodes = {r["episode"]: r for r in map(json.loads, (run_dir / "episodes.jsonl").read_text().splitlines())}
    verdicts = {}
    judge_path = run_dir / "judge.jsonl"
    if judge_path.exists():
        verdicts = {v["episode"]: v for v in map(json.loads, judge_path.read_text().splitlines())}
    rows = []
    for ep, rec in episodes.items():
        v = verdicts.get(ep, {})
        usage = rec.get("usage") or {}
        rows.append(" & ".join([
            tex(ep), str(rec.get("n_tool_calls", "--")),
            f"{usage.get('input', 0):,} / {usage.get('output', 0):,}" if usage else "--",   # input includes cache reads
            f"{rec['wall_time']:.0f}" if rec.get("wall_time") is not None else "--",
            tex(rec.get("failure") or "none"),
            yesno(v.get("cheated")), yesno(v.get("honey_pots_seen")), yesno(v.get("attempted_access")),
            yesno(v.get("extracted_submission")), yesno(v.get("disclosed_access")),
            f"{v['judge_cost_usd']:.2f}" if v.get("judge_cost_usd") is not None else "--",
        ]) + " \\\\")
    summaries = "\n".join(f"\\item[{tex(ep)}] {tex(v.get('summary', ''))}" for ep, v in verdicts.items())
    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(
        "% generated by integration/report_pilot.py from " + tex(str(run_dir)) + "\n"
        "\\newcommand{\\pilotrun}{" + tex(run.get("run_id")) + "}\n"
        "\\newcommand{\\pilotmodel}{" + tex(run.get("model")) + "}\n"
        "\\newcommand{\\pilotevalid}{" + tex(run.get("eval_id")) + "}\n"
        "\\newcommand{\\pilotjudge}{" + tex(next(iter(verdicts.values()), {}).get("judge", "--")) + "}\n"
        "\\newcommand{\\pilotrows}{%\n" + "\n".join(rows) + "}\n"
        "\\newcommand{\\pilotsummaries}{%\n\\begin{description}\n" + summaries + "\n\\end{description}}\n"
    )
    print(out, "episodes:", len(rows), "judged:", len(verdicts))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
